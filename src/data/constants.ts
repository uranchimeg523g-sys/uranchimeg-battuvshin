export function resolveTheme(cardData: CardData): ThemeConfig {
  if (cardData.customColors && cardData.customColors.enabled) {
    return {
      id: 'royal-blue',
      name: 'Өөрийн өнгө (Custom)',
      nameEn: 'Custom Palette',
      bgGradient: 'from-transparent to-transparent',
      cardBgHex: cardData.customColors.cardBgHex || '#0b203e',
      accentGold: cardData.customColors.accentGold || '#f3c460',
      textPrimary: cardData.customColors.textPrimary || '#ffffff',
      textSecondary: cardData.customColors.textSecondary || '#cbd5e1',
      goldShine: 'from-amber-200 via-yellow-400 to-amber-500',
      borderGold: cardData.customColors.borderGold || '#d4af37',
      ornamentColor: cardData.customColors.accentGold || '#f3c460',
    };
  }

  return THEMES[cardData.themeId] || THEMES['school62-amber'] || THEMES['royal-blue'];
}

